-- "아직 안 보냈다"와 "보냈는데 모른다"를 가른다 (Phase 6.5, 격벽).
--
-- 둘은 전혀 다른 상태다.
--
--   sent = 1   보냈는데 답이 없다. <b>돈이 나갔을 수 있다.</b> 조회로 확인해야 한다
--   sent = 0   격벽에 막혀 보내지도 못했다. 돈은 안 나갔다. 그냥 보내면 된다
--
-- 섞으면 안 된다. 안 보낸 건을 "모른다"고 알리면 없는 사고를 보고하는 것이고,
-- 보낸 건을 "안 보냈다"고 보면 이중 지급이 된다.
--
-- 기존 행은 전부 "보냈는데 모른다"였다 — 격벽이 없던 시절에는 그 상태밖에 없었다.
ALTER TABLE pending_external_credits
    ADD COLUMN sent TINYINT(1) NOT NULL DEFAULT 1;
