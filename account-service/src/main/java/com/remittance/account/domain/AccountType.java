package com.remittance.account.domain;

public enum AccountType {
	PERSONAL,
	BUSINESS,

	/**
	 * 상대 은행과의 <b>정산 계좌</b> (Phase 6.5). 고객 계좌가 아니라 <b>우리 장부상의 자리</b>다.
	 *
	 * <p>왜 필요한가 — 외부로 나가는 송금은 받는 쪽이 우리 계좌가 아니다. 그런데 원장은
	 * 송금 한 건에 <b>두 다리</b>가 모여야 종결로 본다. 상대 계좌를 우리 원장에 적을 수는 없으니,
	 * 대신 <b>"이 은행에 지급할 채무"</b>를 담는 계좌를 두고 그쪽으로 적는다.
	 *
	 * <pre>
	 *   고객 계좌  −50,000  ─┐
	 *                        ├─ 우리 원장에 두 다리 (원장·대사 로직 그대로)
	 *   KB 정산계좌 +50,000  ─┘
	 * </pre>
	 *
	 * <p>실제 은행이 하는 방식이다(nostro/vostro). 정산 계좌의 잔액은 곧
	 * <b>그 은행에 아직 넘기지 않은 돈</b>이고, 실제 정산이 끝나면 줄어든다.
	 *
	 * <p><b>대가</b>: 그 은행으로 가는 모든 송금이 계좌 하나에 몰린다 — 전형적인 핫 계좌다.
	 * 다만 Phase 6에서 잔액 샤딩을 이미 만들어뒀으므로 대응 수단은 갖고 있다.
	 */
	SETTLEMENT
}
