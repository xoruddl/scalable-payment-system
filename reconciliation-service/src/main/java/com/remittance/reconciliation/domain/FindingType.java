package com.remittance.reconciliation.domain;

/** 대사가 찾아낼 수 있는 어긋남의 종류. */
public enum FindingType {

	/**
	 * 계좌 잔액과 원장 합이 다르다. <b>돈이 실제로 어긋난 것</b>이라 가장 무겁다.
	 * 잔액 변경 이벤트가 원장에 닿지 못했거나(DLT), 원장에 없는 경로로 잔액이 바뀐 경우다.
	 */
	BALANCE_MISMATCH,

	/**
	 * 송금이 종결되지 못한 채 오래 남아 있다. Saga가 어디선가 끊겼다는 뜻이다.
	 * 돈이 뜬 채로 멈춰 있을 수 있다(보상까지 실패한 경우).
	 */
	UNSETTLED_TRANSFER,

	/**
	 * 멱등성 키가 IN_PROGRESS로 남아 재요청이 계속 막힌다.
	 * 돈이 어긋난 건 아니지만 사용자는 송금을 못 한다.
	 */
	STRANDED_IDEMPOTENCY_KEY,

	/**
	 * 상대 은행에 <b>보냈는데</b> 오래도록 결과를 모른다 (Phase 6.5).
	 *
	 * <p><b>우리도 상대도 모르는 돈</b>이다. 확인 루프가 계속 물어보고 있지만 상대가 답을 못 주면
	 * 기계는 여기서 더 나아갈 수 없다 — 재시도하면 이중 입금이고, 실패로 처리하면 돈이 사라진다.
	 * <b>사람이 상대 은행에 연락해야 하는 유일한 종류</b>라 따로 센다.
	 *
	 * <p>회로나 격벽에 막혀 <b>못 보낸</b> 건은 여기 들어오지 않는다. 돈이 나가지 않았으므로
	 * 사고가 아니라 밀린 일이고, 상대가 살아나면 저절로 빠진다.
	 */
	UNKNOWN_EXTERNAL_CREDIT
}
